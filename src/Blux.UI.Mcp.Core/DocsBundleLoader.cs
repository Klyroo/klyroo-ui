using System.Reflection;
using System.Text.Json;
using Blux.UI.Mcp.Model;

namespace Blux.UI.Mcp;

/// <summary>Reads the docs bundle embedded in this assembly at build time.</summary>
public static class DocsBundleLoader
{
    public const string ResourceName = "docs-bundle.json";

    private static readonly Lazy<DocsBundle> EmbeddedBundle = new(() =>
    {
        using var stream = typeof(DocsBundleLoader).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"The docs bundle ({ResourceName}) is not embedded in {typeof(DocsBundleLoader).Assembly.GetName().Name}.");
        return Load(stream);
    });

    /// <summary>The bundle generated by the build of this assembly.</summary>
    public static DocsBundle Embedded => EmbeddedBundle.Value;

    public static DocsBundle Load(Stream json) =>
        JsonSerializer.Deserialize<DocsBundle>(json, DocsBundle.JsonOptions)
            ?? throw new InvalidDataException("The docs bundle is empty.");

    /// <summary>The version of the library the bundle documents, with the build metadata of the assembly left out.</summary>
    public static string AssemblyVersion(Assembly assembly)
    {
        var info = assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion ?? "0.0.0";
        var plus = info.IndexOf('+');
        return plus < 0 ? info : info[..plus];
    }
}
