namespace Klyroo.UI;

/// <summary>The element a <see cref="KlyDashboardNavbar"/> renders as.</summary>
public enum DashboardNavbarElement
{
    /// <summary>A <c>header</c>: the banner landmark of the page when it sits outside any sectioning element, so a page has one.</summary>
    Header,
    /// <summary>A <c>div</c>, for the second navbar of a page, such as the one of a detail panel next to a list.</summary>
    Div,
}
