namespace Klyroo.UI;

/// <summary>The <c>type</c> attribute of a <see cref="KlyButton"/>.</summary>
public enum ButtonType
{
    /// <summary>Does nothing by itself, even inside a form (the default).</summary>
    Button,
    /// <summary>Submits the form it belongs to.</summary>
    Submit,
    /// <summary>Resets the form it belongs to.</summary>
    Reset,
}
