using System.Reflection;
using Lux.UI.Theming;

namespace Lux.UI.ClassExtractor;

/// <summary>
/// Writes the class list the Tailwind build compiles, from the default themes:
/// <c>styles/generated/classes.txt</c> (scanned by <c>styles/lux.css</c>, mode without Tailwind) and
/// <c>wwwroot/&lt;theme css&gt;</c> (tokens and <c>@source inline(...)</c> for apps compiling Tailwind themselves).
/// </summary>
/// <remarks>
/// usage: <c>Lux.UI.ClassExtractor &lt;package root&gt; [--assembly &lt;dll&gt;]... [--extension &lt;type name&gt;]... [--only-extensions] [--theme-css &lt;file name&gt;]</c>
/// <list type="bullet">
/// <item><c>--assembly</c> only loads an assembly (repeatable), so a type name below can be resolved from it.</item>
/// <item><c>--extension</c> names an options class of a sister package, by assembly-qualified or full name (repeatable). It is registered
/// with <see cref="LuxOptions.Extension(Type)"/> and its themes join the list. Nothing else is instantiated.</item>
/// <item><c>--only-extensions</c> leaves the themes of Lux.UI out and writes a theme css holding only the <c>@source inline(...)</c> of the
/// extensions: the tokens come from <c>lux.theme.css</c> of the core.</item>
/// <item><c>--theme-css</c> is the file written in <c>wwwroot/</c>, <c>lux.theme.css</c> by default.</item>
/// </list>
/// </remarks>
public static class Extractor
{
    private const string Usage = "usage: Lux.UI.ClassExtractor <package root> [--assembly <dll>]... [--extension <type name>]... [--only-extensions] [--theme-css <file name>]";

    public static int Run(string[] args, TextWriter output, TextWriter error)
    {
        var positional = new List<string>();
        var assemblies = new List<string>();
        var extensions = new List<string>();
        var onlyExtensions = false;
        var themeCssName = "lux.theme.css";
        for (var i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--assembly" when i + 1 < args.Length: assemblies.Add(args[++i]); break;
                case "--extension" when i + 1 < args.Length: extensions.Add(args[++i]); break;
                case "--theme-css" when i + 1 < args.Length: themeCssName = args[++i]; break;
                case "--only-extensions": onlyExtensions = true; break;
                default: positional.Add(args[i]); break;
            }
        }
        if (positional.Count != 1 || (onlyExtensions && extensions.Count == 0) || (assemblies.Count > 0 && extensions.Count == 0))
        {
            error.WriteLine(Usage);
            return 1;
        }

        var root = Path.GetFullPath(positional[0]);
        var loaded = assemblies.Select(path => Assembly.LoadFrom(Path.GetFullPath(path))).ToList();
        var options = new LuxOptions();
        foreach (var name in extensions)
        {
            var type = Resolve(name, loaded);
            if (type is null)
            {
                error.WriteLine($"Extension type '{name}' not found. Pass the assembly with --assembly, or an assembly-qualified name.");
                return 1;
            }
            try
            {
                options.Extension(type);
            }
            catch (ArgumentException e)
            {
                error.WriteLine(e.Message);
                return 1;
            }
        }

        var classes = onlyExtensions
            ? options.Extensions.SelectMany(LuxOptions.NamedThemesOf).SelectMany(t => t.Value.AllClassTokens())
                .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList()
            : ThemeCatalog.AllClassTokens(options);

        var generated = Path.Combine(root, "styles", "generated");
        Directory.CreateDirectory(generated);
        File.WriteAllText(Path.Combine(generated, "classes.txt"), string.Join('\n', classes) + "\n");

        var source = $"@source inline(\"{string.Join(' ', classes)}\");\n";
        var themeCss = onlyExtensions
            ? "/* Classes of the Lux.UI extension themes, for apps that compile Tailwind v4 themselves (the tokens come from lux.theme.css). Generated by build/Lux.UI.ClassExtractor, do not edit. */\n" + source
            : "/* Lux.UI for apps that compile Tailwind v4 themselves. Generated by build/Lux.UI.ClassExtractor, do not edit. */\n" +
              File.ReadAllText(Path.Combine(root, "styles", "lux.base.css")).TrimEnd() + "\n\n" + source;
        Directory.CreateDirectory(Path.Combine(root, "wwwroot"));
        File.WriteAllText(Path.Combine(root, "wwwroot", themeCssName), themeCss);

        output.WriteLine($"{classes.Count} classes written.");
        return 0;
    }

    // An assembly-qualified name resolves by itself; a full name is looked up in the assemblies given with --assembly, then in Lux.UI.
    private static Type? Resolve(string name, IEnumerable<Assembly> assemblies)
    {
        var type = Type.GetType(name, throwOnError: false);
        if (type is not null) return type;
        return assemblies.Append(typeof(LuxOptions).Assembly).Select(a => a.GetType(name, throwOnError: false)).FirstOrDefault(t => t is not null);
    }
}
