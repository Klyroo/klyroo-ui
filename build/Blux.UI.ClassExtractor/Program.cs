using System.Reflection;
using Blux.UI;
using Blux.UI.Theming;

// Writes the class list the Tailwind build compiles, from the default themes:
//   styles/generated/classes.txt  scanned by styles/blux.css (mode without Tailwind)
//   wwwroot/<theme css>           tokens + @source inline(...) for apps compiling Tailwind themselves
//
// usage: Blux.UI.ClassExtractor <package root> [--assembly <dll>]... [--only-extensions] [--theme-css <file name>]
//   <package root>      the folder of the package (src/Blux.UI for the core), holding styles/ and wwwroot/.
//   --assembly <dll>    an assembly of a sister package: every public options class of it with a public ComponentTheme property
//                       is registered with BluxOptions.Extension and its themes join the list. Repeatable.
//   --only-extensions   leave the themes of Blux.UI out: the list is the one of the extension assemblies only (a sister package
//                       compiles its own classes next to the ones of the core).
//   --theme-css <name>  the file written in wwwroot/. Defaults to blux.theme.css.
var positional = new List<string>();
var assemblies = new List<string>();
var onlyExtensions = false;
var themeCssName = "blux.theme.css";
for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--assembly" when i + 1 < args.Length: assemblies.Add(args[++i]); break;
        case "--theme-css" when i + 1 < args.Length: themeCssName = args[++i]; break;
        case "--only-extensions": onlyExtensions = true; break;
        default: positional.Add(args[i]); break;
    }
}
if (positional.Count != 1 || (onlyExtensions && assemblies.Count == 0))
{
    Console.Error.WriteLine("usage: Blux.UI.ClassExtractor <package root> [--assembly <dll>]... [--only-extensions] [--theme-css <file name>]");
    return 1;
}

var root = Path.GetFullPath(positional[0]);
var options = new BluxOptions();
foreach (var path in assemblies)
{
    var assembly = Assembly.LoadFrom(Path.GetFullPath(path));
    foreach (var type in ExtensionTypes(assembly)) options.Extension(type);
}

var classes = onlyExtensions
    ? options.Extensions.SelectMany(BluxOptions.NamedThemesOf).SelectMany(t => t.Value.AllClassTokens())
        .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList()
    : ThemeCatalog.AllClassTokens(options);

var generated = Path.Combine(root, "styles", "generated");
Directory.CreateDirectory(generated);
File.WriteAllText(Path.Combine(generated, "classes.txt"), string.Join('\n', classes) + "\n");

var baseCss = File.ReadAllText(Path.Combine(root, "styles", "blux.base.css"));
var themeCss =
    "/* Blux UI for apps that compile Tailwind v4 themselves. Generated by build/Blux.UI.ClassExtractor, do not edit. */\n" +
    baseCss.TrimEnd() + "\n\n" +
    $"@source inline(\"{string.Join(' ', classes)}\");\n";
File.WriteAllText(Path.Combine(root, "wwwroot", themeCssName), themeCss);

Console.WriteLine($"{classes.Count} classes written.");
return 0;

static IEnumerable<Type> ExtensionTypes(Assembly assembly) =>
    assembly.GetExportedTypes()
        .Where(t => t.IsClass && !t.IsAbstract && t != typeof(BluxOptions) && t.GetConstructor(Type.EmptyTypes) is not null)
        .Where(t => BluxOptions.NamedThemesOf(Activator.CreateInstance(t)!).Any())
        .OrderBy(t => t.FullName, StringComparer.Ordinal);
