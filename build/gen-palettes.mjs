// Generates src/Lux.UI/Theming/BxPalette.Tailwind.cs from Tailwind's default theme (oklch values kept as they are).
// Run after upgrading tailwindcss:  node build/gen-palettes.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const version = JSON.parse(readFileSync('node_modules/tailwindcss/package.json', 'utf8')).version;
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const names = [...css.matchAll(/--color-([a-z]+)-50:/g)].map(m => m[1]);

const pascal = n => n[0].toUpperCase() + n.slice(1);
let out = `// <auto-generated>Generated by build/gen-palettes.mjs from tailwindcss ${version}. Do not edit.</auto-generated>
namespace Lux.UI;

public sealed partial class BxPalette
{
`;
const all = [];
for (const name of names) {
  const values = shades.map(s => {
    const m = css.match(new RegExp(`--color-${name}-${s}:\\s*([^;]+);`));
    if (!m) throw new Error(`missing ${name}-${s}`);
    return m[1].trim();
  });
  out += `    /// <summary>Tailwind CSS v4 <c>${name}</c> palette.</summary>\n`;
  out += `    public static BxPalette ${pascal(name)} { get; } = Tailwind("${name}", ${values.map(v => `"${v}"`).join(', ')});\n\n`;
  all.push(pascal(name));
}
out += `    /// <summary>Every Tailwind CSS v4 default palette, in Tailwind's order.</summary>\n    public static IReadOnlyList<BxPalette> TailwindPalettes { get; } = [${all.join(', ')}];\n}\n`;
writeFileSync('src/Lux.UI/Theming/BxPalette.Tailwind.cs', out);
console.log(names.length + ' palettes');
