// Generates src/Klyroo.UI.Maui/Icons/BuiltinIcons.g.cs from the Lucide icons that Klyroo.UI embeds
// (src/Klyroo.UI/Components/Icon/BuiltinIcons.g.cs): each icon becomes a list of SVG path data strings
// (24x24, stroke 2, round caps and joins), which a MAUI Path can draw. Run: node build/gen-maui-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src/Klyroo.UI/Components/Icon/BuiltinIcons.g.cs'), 'utf8');

const num = (v) => Number.parseFloat(v);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-z-]+)=\\?"([^"\\]*)\\?"/g)].map((m) => [m[1], m[2]]));
const fmt = (n) => String(Math.round(n * 1000) / 1000);

function rect(a) {
  const x = num(a.x ?? 0), y = num(a.y ?? 0), w = num(a.width), h = num(a.height);
  const rx = Math.min(num(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(num(a.ry ?? a.rx ?? 0), h / 2);
  if (!rx && !ry) return `M${fmt(x)} ${fmt(y)}H${fmt(x + w)}V${fmt(y + h)}H${fmt(x)}Z`;
  return `M${fmt(x + rx)} ${fmt(y)}H${fmt(x + w - rx)}A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x + w)} ${fmt(y + ry)}V${fmt(y + h - ry)}`
    + `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x + w - rx)} ${fmt(y + h)}H${fmt(x + rx)}A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x)} ${fmt(y + h - ry)}`
    + `V${fmt(y + ry)}A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x + rx)} ${fmt(y)}Z`;
}
const ellipse = (cx, cy, rx, ry) =>
  `M${fmt(cx - rx)} ${fmt(cy)}A${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(cx + rx)} ${fmt(cy)}A${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(cx - rx)} ${fmt(cy)}Z`;

function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'rect': return rect(a);
    case 'circle': return ellipse(num(a.cx), num(a.cy), num(a.r), num(a.r));
    case 'ellipse': return ellipse(num(a.cx), num(a.cy), num(a.rx), num(a.ry));
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': return 'M' + a.points.trim().replace(/\s+/g, ' ').replace(/ /g, ' L').replace(/^L/, '');
    case 'polygon': return 'M' + a.points.trim().replace(/\s+/g, ' ').replace(/ /g, ' L').replace(/^L/, '') + 'Z';
    default: throw new Error(`unsupported element <${tag}>`);
  }
}

const entries = [...source.matchAll(/\["([a-z0-9-]+)"\] = "((?:[^"\\]|\\.)*)",/g)];
const lines = [];
for (const [, name, body] of entries) {
  const paths = [...body.matchAll(/<(path|rect|circle|ellipse|line|polyline|polygon)\s+((?:[^>\\]|\\.)*?)\/?>/g)]
    .map((m) => toPath(m[1], attrs(m[2])));
  if (!paths.length) throw new Error(`no shape in ${name}`);
  lines.push(`        ["${name}"] = [${paths.map((p) => `"${p}"`).join(', ')}],`);
}

const header = source.slice(0, source.indexOf('/// <summary>'))
  .replace('namespace Klyroo.UI;', 'namespace Klyroo.UI.Maui;')
  .replace('Generated by build/gen-icons.mjs', 'Generated by build/gen-maui-icons.mjs');
writeFileSync(join(root, 'src/Klyroo.UI.Maui/Icons/BuiltinIcons.g.cs'), `${header}/// <summary>The Lucide icons embedded in the library: SVG path data (24x24, stroke 2, round caps), by Lucide name. One string per shape.</summary>
internal static class BuiltinIcons
{
    public const double Size = 24;
    public const double StrokeWidth = 2;

    public static readonly IReadOnlyDictionary<string, string[]> Lucide = new Dictionary<string, string[]>(StringComparer.Ordinal)
    {
${lines.join('\n')}
    };
}
`);
console.log(`${lines.length} icons`);
