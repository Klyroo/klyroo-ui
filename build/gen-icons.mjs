writeFileSync(join(root, 'src/Blux.UI/Components/Icon/BuiltinIcons.g.cs'), builtin);

const prefixes = Object.keys(collections).sort();
const prefixFile = `// <auto-generated>
// Generated by build/gen-icons.mjs from @iconify/collections ${read('node_modules/@iconify/collections/package.json').version}: do not edit. Run \`npm run build\`.
// </auto-generated>
#if BLUX_TASKS
namespace Blux.UI.Build
#else
namespace Blux.UI.Internal
#endif
{
    /// <summary>The prefixes of the Iconify collections, which the \`i-{prefix}-{name}\` form is resolved against (the longest match wins).</summary>
    internal static class IconCollections
    {
        public static readonly string[] Prefixes =
        {
${prefixes.map((p) => `            ${q(p)},`).join('\n')}
        };

        /// <summary>The Lucide icons Blux.UI embeds: the build task does not download them (same release as the library).</summary>
        public static readonly string[] BuiltinLucide =
        {
${sorted.map((p) => `            ${q(p)},`).join('\n')}
        };
    }
}
`;
mkdirSync(join(root, 'src/Blux.UI.Build.Tasks/Icons'), { recursive: true });
writeFileSync(join(root, 'src/Blux.UI.Build.Tasks/Icons/IconCollections.g.cs'), prefixFile);
console.log(`gen-icons: ${sorted.length} built-in icons, ${prefixes.length} collection prefixes`);
