// Generates the icon data Blux.UI and its build task embed:
//   src/Blux.UI/Components/Icon/BuiltinIcons.g.cs        the Lucide icons of build/builtin-icons.json, from @iconify-json/lucide
//   src/Blux.UI.Build.Tasks/Icons/IconCollections.g.cs   the prefixes of every Iconify collection, from @iconify/collections
// Part of `npm run build`; the results are committed. Lucide is distributed under the ISC license, kept in the header.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const lucide = read('node_modules/@iconify-json/lucide/icons.json');
const info = read('node_modules/@iconify-json/lucide/info.json');
const collections = read('node_modules/@iconify/collections/collections.json');
const names = read('build/builtin-icons.json').icons;

const q = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

function resolve(name, depth = 0) {
  if (depth > 5) throw new Error(`Alias loop at ${name}`);
  const icon = lucide.icons[name];
  if (icon) return icon;
  const alias = lucide.aliases?.[name];
  if (!alias) throw new Error(`Lucide has no icon named "${name}" (build/builtin-icons.json)`);
  if (alias.hFlip || alias.vFlip || alias.rotate) throw new Error(`Alias "${name}" needs a transformation, which this generator does not apply`);
  return resolve(alias.parent, depth + 1);
}

const width = lucide.width ?? 24;
const height = lucide.height ?? 24;
const sorted = [...new Set(names)].sort();
const rows = sorted.map((n) => {
  const icon = resolve(n);
  if ((icon.width ?? width) !== 24 || (icon.height ?? height) !== 24 || icon.left || icon.top) throw new Error(`${n} is not 24x24`);
  return `        [${q(n)}] = ${q(icon.body)},`;
});

